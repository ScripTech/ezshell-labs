/**
 * Example: Integration with User Registration
 * This shows how to integrate the email service with your user registration flow
 */

import { emailNotificationService } from '@/services/email/EmailNotificationService';
import { NextRequest, NextResponse } from 'next/server';

export async function POST(request: NextRequest) {
  try {
    const { email, name, verificationToken } = await request.json();

    // Create user in database (your existing logic)
    const user = {
      id: 'user_123', // Generated by your user creation logic
      name,
      email,
      role: 'user' as const
    };

    // Send account validation email
    const verificationUrl = `${process.env.NEXTAUTH_URL}/verify?token=${verificationToken}`;

    await emailNotificationService.sendAccountValidation(
      user,
      verificationToken,
      verificationUrl
    );

    return NextResponse.json({
      success: true,
      message: 'User created and verification email sent',
      userId: user.id
    });

  } catch (error) {
    console.error('Registration error:', error);
    return NextResponse.json(
      {
        success: false,
        error: 'Registration failed',
        details: error instanceof Error ? error.message : 'Unknown error'
      },
      { status: 500 }
    );
  }
}

/**
 * Example: Integration with Lab Provisioning
 * This shows how to send lab notifications during the provisioning process
 */

export async function sendLabNotifications(userId: string, labInfo: any) {
  try {
    // Get user from database (your existing logic)
    const user = await getUserById(userId); // Your function

    // Send lab provisioning notification
    await emailNotificationService.sendLabProvisioning(user, {
      name: labInfo.name,
      description: labInfo.description,
      estimatedTime: '15-20 minutes',
      provisioningSteps: [
        'Creating AWS VPC and subnets',
        'Launching EC2 instances',
        'Configuring security groups',
        'Setting up SSH access',
        'Preparing lab materials'
      ]
    });

    // After lab is ready, send ready notification
    setTimeout(async () => {
      await emailNotificationService.sendLabReady(user, {
        name: labInfo.name,
        description: labInfo.description,
        accessUrl: `https://lab.ezshell-labs.com/access/${labInfo.id}`,
        duration: '2 hours',
        expiresAt: new Date(Date.now() + 2 * 60 * 60 * 1000)
      });
    }, 5000); // Simulate 5-second provisioning time

  } catch (error) {
    console.error('Lab notification error:', error);
  }
}

